def get_model_matrix(data, feature_columns):
    """Return the exact feature columns expected by the saved notebook model."""
    missing = [column for column in feature_columns if column not in data.columns]
    if missing:
        raise ValueError(
            "The model requires columns missing from the dataset: "
            + ", ".join(missing)
        )

    matrix = data.loc[:, feature_columns].copy()

    for column in matrix.columns:
        matrix[column] = pd.to_numeric(matrix[column], errors="coerce")

    if matrix.isna().any().any():
        matrix = matrix.fillna(matrix.median(numeric_only=True)).fillna(0)

    return matrix


def evaluate_model(name, y_true, y_pred):
    """Calculate the evaluation metrics used in the supplied notebook."""
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))

    nonzero = y_true != 0
    if nonzero.any():
        mape = np.mean(
            np.abs((y_true[nonzero] - y_pred[nonzero]) / y_true[nonzero])
        ) * 100
    else:
        mape = np.nan

    r2 = r2_score(y_true, y_pred)

    return {
        "Model": name,
        "MAE": mae,
        "RMSE": rmse,
        "MAPE": mape,
        "R2": r2,
    }


def _forecast_features(frame):
    """Create leakage-free calendar/weather features shared by training and forecasting."""
    out = pd.DataFrame(index=frame.index)
    dates = pd.to_datetime(frame["dteday"], errors="coerce")
    hours = pd.to_numeric(frame["hr"], errors="coerce").fillna(0).astype(int).clip(0, 23)
    months = pd.to_numeric(frame["mnth"], errors="coerce")
    if months.isna().any():
        months = dates.dt.month.fillna(1)
    weekdays = pd.to_numeric(frame["weekday"], errors="coerce")
    if weekdays.isna().any():
        weekdays = ((dates.dt.dayofweek + 1) % 7).fillna(0)
    out["hour_sin"] = np.sin(2 * np.pi * hours / 24.0)
    out["hour_cos"] = np.cos(2 * np.pi * hours / 24.0)
    out["month_sin"] = np.sin(2 * np.pi * (months - 1) / 12.0)
    out["month_cos"] = np.cos(2 * np.pi * (months - 1) / 12.0)
    out["weekday_sin"] = np.sin(2 * np.pi * weekdays / 7.0)
    out["weekday_cos"] = np.cos(2 * np.pi * weekdays / 7.0)
    for col in ["season", "yr", "holiday", "workingday", "weathersit", "temp", "atemp", "hum", "windspeed"]:
        if col in frame.columns:
            out[col] = pd.to_numeric(frame[col], errors="coerce")
    # Extra calendar indicators help the model learn commute/weekend demand.
    out["is_weekend"] = (pd.to_numeric(frame.get("weekday", 0), errors="coerce").fillna(0).isin([0, 6])).astype(int)
    out["is_rush_hour"] = hours.isin([7, 8, 9, 16, 17, 18, 19]).astype(int)
    return out.replace([np.inf, -np.inf], np.nan)


def _future_calendar(history, periods):
    """Build complete future timestamps and realistic weather proxies from historical patterns."""
    hist = history.copy()
    hist["dteday"] = pd.to_datetime(hist["dteday"], errors="coerce")
    hist["hr"] = pd.to_numeric(hist["hr"], errors="coerce")
    hist = hist.dropna(subset=["dteday", "hr"]).sort_values(["dteday", "hr"])
    if hist.empty:
        raise ValueError("The dataset contains no valid timestamps for forecasting.")
    last_timestamp = hist["dteday"].dt.normalize() + pd.to_timedelta(hist["hr"], unit="h")
    last_timestamp = last_timestamp.max()
    future_dates = pd.date_range(last_timestamp + pd.Timedelta(hours=1), periods=periods, freq="h")
    future = pd.DataFrame({"dteday": future_dates})
    future["hr"] = future["dteday"].dt.hour
    future["mnth"] = future["dteday"].dt.month
    # Dataset weekday convention: Sunday=0 ... Saturday=6.
    future["weekday"] = (future["dteday"].dt.dayofweek + 1) % 7
    future["yr"] = (future["dteday"].dt.year > hist["dteday"].dt.year.min()).astype(int)
    future["workingday"] = (future["dteday"].dt.dayofweek < 5).astype(int)
    future["holiday"] = 0
    month = future["mnth"]
    future["season"] = np.select([month.isin([1,2,3]), month.isin([4,5,6]), month.isin([7,8,9])], [1,2,3], default=4)
    # No future weather API is included: use month/hour medians, falling back to month then global medians.
    for col in ["weathersit", "temp", "atemp", "hum", "windspeed"]:
        if col not in hist.columns:
            continue
        values = pd.to_numeric(hist[col], errors="coerce")
        hist[col] = values
        month_hour = hist.assign(_month=hist["dteday"].dt.month, _hour=hist["hr"]).groupby(["_month", "_hour"])[col].median()
        month_median = hist.assign(_month=hist["dteday"].dt.month).groupby("_month")[col].median()
        global_median = values.median()
        if pd.isna(global_median):
            global_median = 0
        future[col] = [month_hour.get((int(m), int(h)), np.nan) for m, h in zip(future["mnth"], future["hr"])]
        future[col] = future[col].fillna(future["mnth"].map(month_median)).fillna(global_median)
    return future


def generate_forecast(data, days, model=None, feature_columns=None):
    """Train a leakage-free forecasting model and generate hourly predictions for 1–30 days.

    `casual` and `registered` are deliberately excluded because they sum to `cnt`.
    Training/evaluation uses only information available before the target hour.
    """
    if data is None or len(data) < 100:
        raise ValueError("At least 100 historical hourly rows are required for a stable forecast.")
    if not 1 <= int(days) <= 30:
        raise ValueError("Forecast duration must be between 1 and 30 days.")
    history = data.copy()
    history["dteday"] = pd.to_datetime(history["dteday"], dayfirst=True, errors="coerce")
    history["cnt"] = pd.to_numeric(history["cnt"], errors="coerce")
    history = history.dropna(subset=["dteday", "cnt", "hr"]).sort_values(["dteday", "hr"])
    history = history.drop_duplicates(subset=["dteday", "hr"], keep="last")
    if len(history) < 100:
        raise ValueError("Not enough valid timestamp/target rows remain after cleaning.")

    # Only predictors that can be known at forecast time. No `instant`, `casual`, or `registered`.
    X = _forecast_features(history)
    y = history["cnt"].astype(float)
    usable = X.notna().all(axis=1) & y.notna() & np.isfinite(y)
    X, y = X.loc[usable], y.loc[usable]
    if len(X) < 100:
        raise ValueError("Not enough complete feature rows to train the forecast model.")

    # Prefer a robust tree ensemble for nonlinear hour/weekend/weather effects.
    forecaster = ExtraTreesRegressor(
        n_estimators=260, min_samples_leaf=2, max_features=0.95,
        random_state=42, n_jobs=-1
    )
    # A chronological validation score is retained for transparent UI reporting.
    split = max(1, int(len(X) * 0.80))
    if split < len(X):
        validation_model = ExtraTreesRegressor(
            n_estimators=180, min_samples_leaf=2, max_features=0.95,
            random_state=42, n_jobs=-1
        )
        validation_model.fit(X.iloc[:split], y.iloc[:split])
        valid_pred = np.maximum(0, validation_model.predict(X.iloc[split:]))
        st.session_state["bike_forecast_validation"] = {
            "MAE": float(mean_absolute_error(y.iloc[split:], valid_pred)),
            "RMSE": float(np.sqrt(mean_squared_error(y.iloc[split:], valid_pred))),
            "R2": float(r2_score(y.iloc[split:], valid_pred)) if len(y.iloc[split:]) > 1 else float("nan"),
            "train_rows": int(split), "validation_rows": int(len(X) - split),
        }
    forecaster.fit(X, y)

    future = _future_calendar(history, int(days) * 24)
    future_X = _forecast_features(future)
    # Use training medians for any missing predictor; columns are aligned by name.
    future_X = future_X.reindex(columns=X.columns)
    future_X = future_X.fillna(X.median(numeric_only=True)).fillna(0)
    predictions = np.maximum(0, forecaster.predict(future_X))
    # Rentals are integer counts; round only after prediction to avoid systematic truncation.
    predictions = np.rint(predictions).astype(int)
    result = pd.DataFrame({"dteday": future["dteday"], "Predicted_cnt": predictions})
    return result


