from sklearn.ensemble import GradientBoostingRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

DATA_PATH = BASE_DIR / "Dataset.csv"
COMPARISON_PATH = BASE_DIR / "model_comparison.csv"
FORECAST_PATH = BASE_DIR / "next_30_days_forecast.csv"

TARGET = "cnt"
FEATURES = [
    "instant", "season", "yr", "mnth", "hr", "holiday", "weekday",
    "workingday", "weathersit", "temp", "atemp", "hum", "windspeed"
]
NUMERIC_COLUMNS = [
    "instant", "yr", "mnth", "hr", "weekday", "temp", "atemp",
    "hum", "windspeed", "cnt", "casual", "registered"
]
CATEGORY_COLUMNS = ["season", "holiday", "workingday", "weathersit"]

@st.cache_data(show_spinner=False)
def load_data(path_string):
    path = Path(path_string)
    if not path.exists():
        raise FileNotFoundError("Dataset.csv must be in the same folder as app.py.")
    data = pd.read_csv(path)
    data.columns = [str(c).strip().lower() for c in data.columns]
    required = ["dteday", "cnt", *FEATURES]
    missing = [c for c in required if c not in data.columns]
    if missing:
        raise ValueError("Dataset is missing required columns: " + ", ".join(missing))
    data = data.replace(["?", "NA", "N/A", "null", "None", ""], np.nan)
    data["dteday"] = pd.to_datetime(data["dteday"], dayfirst=True, errors="coerce")
    for col in NUMERIC_COLUMNS:
        if col in data.columns:
            data[col] = pd.to_numeric(data[col], errors="coerce")
    # Fill text-category gaps with the mode before deterministic category encoding.
    for col in CATEGORY_COLUMNS:
        data[col] = data[col].astype("string").str.strip()
        mode = data[col].mode(dropna=True)
        data[col] = data[col].fillna(mode.iloc[0] if not mode.empty else "Unknown").astype(str)
    # Keep source categorical labels and map them in sorted order, as in LabelEncoder.
    category_maps = {}
    for col in CATEGORY_COLUMNS:
        cats = sorted(data[col].astype(str).unique().tolist())
        category_maps[col] = {v: i for i, v in enumerate(cats)}
        data[col] = data[col].astype(str).map(category_maps[col]).astype(float)
    # Impute numeric values using medians; columns entirely missing become zero.
    for col in data.columns:
        if col == "dteday":
            continue
        if not pd.api.types.is_numeric_dtype(data[col]):
            data[col] = pd.to_numeric(data[col], errors="coerce")
        median = data[col].median(skipna=True)
        data[col] = data[col].fillna(0 if pd.isna(median) else median)
    data = data.dropna(subset=["dteday", TARGET]).drop_duplicates().copy()
    data[TARGET] = data[TARGET].clip(lower=0)
    data = data.sort_values(["dteday", "hr", "instant"]).reset_index(drop=True)
    # Attach the exact category map for future rows without altering source values.
    data.attrs["category_maps"] = category_maps
    if data.empty:
        raise ValueError("Dataset contains no valid timestamp/target rows after cleaning.")
    return data

@st.cache_data(show_spinner=False)
def load_comparison(path_string):
    path = Path(path_string)
    if not path.exists():
        return pd.DataFrame()
    try:
        result = pd.read_csv(path)
        required = {"Model", "MAE", "RMSE", "MAPE", "R2"}
        if not required.issubset(result.columns):
            return pd.DataFrame()
        return result
    except Exception:
        return pd.DataFrame()

@st.cache_resource(show_spinner=False)
def train_forecast_model(dataset_path):
    """Fit the notebook's Gradient Boosting algorithm with leakage-safe features."""
    data = load_data(dataset_path)
    X = data[FEATURES].apply(pd.to_numeric, errors="coerce")
    X = X.fillna(X.median(numeric_only=True)).fillna(0)
    y = pd.to_numeric(data[TARGET], errors="coerce").fillna(data[TARGET].median())
    model = GradientBoostingRegressor(
        n_estimators=500, learning_rate=0.05, max_depth=7,
        subsample=0.8, max_features=0.8, random_state=50
    )
    model.fit(X, y)
    return model

def category_value_for_future(data, column, raw_value):
    """Map future category labels through the same sorted mapping as training."""
    raw = pd.read_csv(DATA_PATH, nrows=0).columns
    # Values were mapped in sorted category order during load_data; rebuild mapping from source.
    source = pd.read_csv(DATA_PATH, usecols=[column])
    vals = source[column].replace(["?", "NA", "N/A", "null", "None", ""], np.nan).dropna().astype(str).str.strip()
    cats = sorted(vals.unique().tolist())
    mapping = {v: i for i, v in enumerate(cats)}
    if raw_value in mapping:
        return float(mapping[raw_value])
    # For unknown future categories, use the closest safe known fallback (most frequent category).
    if not vals.empty:
        mode = vals.mode().iloc[0]
        return float(mapping.get(mode, 0))
    return 0.0

def next_timestamp(last_row):
    stamp = pd.Timestamp(last_row["dteday"]).normalize() + pd.Timedelta(hours=int(last_row["hr"]))
    return stamp + pd.Timedelta(hours=1)

def create_future_features(history, category_maps):
    last = history.iloc[-1]
    future_time = next_timestamp(last)
    row = {c: float(last[c]) for c in FEATURES}
    row["instant"] = float(last["instant"]) + 1
    row["yr"] = float(int(future_time.year > int(history["dteday"].dt.year.min())))
    row["mnth"] = float(future_time.month)
    row["hr"] = float(future_time.hour)
    # UCI bike-sharing weekday convention: Sunday=0, Saturday=6.
    row["weekday"] = float((future_time.dayofweek + 1) % 7)
    row["workingday"] = category_value_for_future(history, "workingday", "Working Day" if future_time.dayofweek < 5 else "No work")
    row["holiday"] = category_value_for_future(history, "holiday", "No")
    # season labels in the provided source are springer, summer, fall, winter.
    season_label = "springer" if future_time.month in (1, 2, 3) else "summer" if future_time.month in (4, 5, 6) else "fall" if future_time.month in (7, 8, 9) else "winter"
    row["season"] = category_value_for_future(history, "season", season_label)
    # No future weather feed is supplied; preserve the most recent observed weather values.
    row["weathersit"] = float(last["weathersit"])
    return pd.DataFrame([{c: row[c] for c in FEATURES}]), future_time, row

def generate_forecast(data, days, model):
    if not 1 <= int(days) <= 30:
        raise ValueError("Forecast duration must be between 1 and 30 days.")
    history = data.copy().sort_values(["dteday", "hr"]).reset_index(drop=True)
    predictions = []
    for _ in range(int(days) * 24):
        X_future, stamp, feature_row = create_future_features(history, {})
        prediction = float(np.asarray(model.predict(X_future)).reshape(-1)[0])
        if not np.isfinite(prediction):
            raise ValueError(f"Non-finite prediction produced for {stamp}.")
        prediction = max(0.0, prediction)
        predictions.append({"Datetime": stamp, "Predicted_cnt": prediction})
        new = {c: np.nan for c in history.columns}
        new.update(feature_row)
        new["dteday"] = stamp.normalize()
        new["hr"] = stamp.hour
        new["cnt"] = prediction
        if "casual" in new: new["casual"] = np.nan
        if "registered" in new: new["registered"] = np.nan
        # Values for every feature used by the model remain populated.
        history = pd.concat([history, pd.DataFrame([new])], ignore_index=True)
        for c in FEATURES:
            if pd.isna(history.loc[history.index[-1], c]):
                history.loc[history.index[-1], c] = feature_row[c]
    return pd.DataFrame(predictions)

