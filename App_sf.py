# ============================================================
# DATASET LOADING AND PREPROCESSING
# Follows the preprocessing steps in BIKE_SHARING_RENTAL.ipynb:
# '?' markers become missing values, selected numeric text columns
# are converted to numeric values, numeric missing values use median,
# categorical missing values use mode, and object features are encoded.
# ============================================================

@st.cache_data(show_spinner=False)
def load_data(path_string):
    data_path = Path(path_string)

    if not data_path.exists():
        raise FileNotFoundError(
            "Dataset.csv was not found. Upload Dataset.csv beside Application.py."
        )

    data = pd.read_csv(data_path)
    data.columns = [str(column).strip() for column in data.columns]

    required_columns = [
        "dteday", "cnt", "instant", "season", "yr", "mnth", "hr",
        "holiday", "weekday", "workingday", "weathersit",
        "temp", "atemp", "hum", "windspeed"
    ]
    missing_columns = [
        column for column in required_columns if column not in data.columns
    ]

    if missing_columns:
        raise ValueError(
            "Dataset.csv is missing columns required by the notebook: "
            + ", ".join(missing_columns)
        )

    data.replace("?", np.nan, inplace=True)

    for column in NUMERIC_TEXT_COLUMNS:
        if column in data.columns:
            data[column] = pd.to_numeric(data[column], errors="coerce")
            median_value = data[column].median()
            if pd.isna(median_value):
                median_value = 0
            data[column] = data[column].fillna(median_value)

    # The notebook converts dteday to datetime before label encoding.
    data["dteday"] = pd.to_datetime(
        data["dteday"], dayfirst=True, errors="coerce"
    )

    if "cnt" in data.columns:
        data["cnt"] = pd.to_numeric(data["cnt"], errors="coerce")

    # Fill remaining categorical values using each column's mode.
    for column in data.select_dtypes(include=["object"]).columns:
        modes = data[column].mode(dropna=True)
        fill_value = modes.iloc[0] if not modes.empty else "Unknown"
        data[column] = data[column].fillna(fill_value).astype(str)

    # Label-encode object columns using sorted category values, matching
    # sklearn LabelEncoder's alphabetical category ordering in the notebook.
    for column in data.select_dtypes(include=["object"]).columns:
        categories = sorted(data[column].astype(str).unique().tolist())
        category_mapping = {
            category: index for index, category in enumerate(categories)
        }
        data[column] = data[column].astype(str).map(category_mapping).astype(int)

    # Convert all non-date columns to numeric values and impute any remaining
    # missing numeric entries using the median.
    for column in data.columns:
        if column != "dteday":
            data[column] = pd.to_numeric(data[column], errors="coerce")
            if data[column].isna().any():
                median_value = data[column].median()
                if pd.isna(median_value):
                    median_value = 0
                data[column] = data[column].fillna(median_value)

    data = data.dropna(subset=["dteday", "cnt"]).copy()
    data = data.sort_values(["dteday", "hr"]).reset_index(drop=True)

    return data


