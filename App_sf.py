def get_model_matrix(data, feature_columns):
    """Return the exact feature columns expected by the saved notebook model."""
    missing = [column for column in feature_columns if column not in data.columns]
    if missing:
        raise ValueError(
            "The model requires columns missing from the dataset: "
            + ", ".join(missing)
        )

    matrix = data.loc[:, feature_columns].copy()

    for column in matrix.columns:
        matrix[column] = pd.to_numeric(matrix[column], errors="coerce")

    if matrix.isna().any().any():
        matrix = matrix.fillna(matrix.median(numeric_only=True)).fillna(0)

    return matrix


def evaluate_model(name, y_true, y_pred):
    """Calculate the evaluation metrics used in the supplied notebook."""
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))

    nonzero = y_true != 0
    if nonzero.any():
        mape = np.mean(
            np.abs((y_true[nonzero] - y_pred[nonzero]) / y_true[nonzero])
        ) * 100
    else:
        mape = np.nan

    r2 = r2_score(y_true, y_pred)

    return {
        "Model": name,
        "MAE": mae,
        "RMSE": rmse,
        "MAPE": mape,
        "R2": r2,
    }


def create_future_row(history, feature_columns):
    """
    Build one future hourly feature row following the notebook's recursive
    forecast idea. The source notebook carries forward the latest weather
    and temperature values because future weather observations are unavailable.
    """
    if history.empty:
        raise ValueError("The dataset contains no history for forecasting.")

    last_row = history.iloc[-1]

    last_timestamp = pd.Timestamp(last_row["dteday"]).normalize()
    if "hr" in history.columns:
        last_timestamp += pd.Timedelta(hours=int(last_row["hr"]))

    future_time = last_timestamp + pd.Timedelta(hours=1)
    row = {}

    for column in feature_columns:
        if column in history.columns:
            row[column] = last_row[column]

    row["instant"] = float(last_row["instant"]) + 1
    row["hr"] = future_time.hour
    # The source dataset's weekday coding uses Sunday=0, Saturday=6.
    row["weekday"] = (future_time.dayofweek + 1) % 7
    row["mnth"] = future_time.month

    # In the notebook, year was label-encoded alphabetically: 2011 -> 0,
    # 2012 -> 1. Use that encoding for future timestamps.
    first_observed_year = int(pd.to_datetime(history["dteday"]).dt.year.min())
    row["yr"] = int(future_time.year > first_observed_year)

    row["workingday"] = 0 if future_time.dayofweek in (5, 6) else 1
    row["holiday"] = 0

    # Notebook LabelEncoder sorted season labels alphabetically:
    # fall=0, springer=1, summer=2, winter=3.
    month = future_time.month
    if month in (1, 2, 3):
        row["season"] = 1
    elif month in (4, 5, 6):
        row["season"] = 2
    elif month in (7, 8, 9):
        row["season"] = 0
    else:
        row["season"] = 3

    # Retain latest observed weather conditions because no future weather
    # dataset is included in the provided notebook resources.
    for column in ["temp", "atemp", "hum", "windspeed", "weathersit"]:
        if column in history.columns:
            row[column] = last_row[column]

    missing_columns = [
        column for column in feature_columns if column not in row
    ]
    if missing_columns:
        raise ValueError(
            "Cannot build forecast row. Missing model features: "
            + ", ".join(missing_columns)
        )

    future_X = pd.DataFrame(
        [{column: row[column] for column in feature_columns}]
    )

    for column in future_X.columns:
        future_X[column] = pd.to_numeric(future_X[column], errors="coerce")

    future_X = future_X.fillna(0)

    return future_X, future_time, row


def generate_forecast(data, days, model, feature_columns):
    """Generate recursive hourly rental predictions with the saved GBR model."""
    if len(data) < 1:
        raise ValueError("At least one historical row is required.")

    history = data.copy()
    predictions = []

    for _ in range(int(days) * 24):
        future_X, future_time, feature_row = create_future_row(
            history, feature_columns
        )

        predicted_count = float(np.asarray(model.predict(future_X))[0])
        predicted_count = max(0.0, predicted_count)

        predictions.append({
            "dteday": future_time,
            "Predicted_cnt": predicted_count,
        })

        new_row = {column: np.nan for column in history.columns}
        for column, value in feature_row.items():
            if column in new_row:
                new_row[column] = value

        new_row["dteday"] = future_time
        new_row["cnt"] = predicted_count
        if "casual" in new_row:
            new_row["casual"] = np.nan
        if "registered" in new_row:
            new_row["registered"] = np.nan

        history = pd.concat(
            [history, pd.DataFrame([new_row])],
            ignore_index=True
        )

    return pd.DataFrame(predictions)


